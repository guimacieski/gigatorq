"""Build validated SQL seed files from the JSON product files in db/data/.

Usage:  python db/tools/build_seed.py
Output: db/seed/10_<name>.sql for every db/data/<name>.json

Each JSON file is a list of tools. Every tool lists its specs as
  [spec_key, qualifier, value, raw_text, "M" (manufacturer) or "R" (retailer), source_url]
where value is a number, [min, max], true/false, or a string (for text/enum specs).
Lookups use slugs (brand, category, platform, product line, feature), so seed files
do not depend on numeric ids. The script loads schema + all seeds into an in-memory
SQLite database and refuses to write anything that does not validate.
"""
import glob, json, os, sqlite3, sys

DB_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TODAY = '2026-10-22'

def q(v):
    if v is None: return 'NULL'
    if isinstance(v, bool): return '1' if v else '0'
    if isinstance(v, (int, float)): return repr(v)
    return "'" + str(v).replace("'", "''") + "'"

def sel(table, col, val):
    return 'NULL' if val is None else f"(SELECT id FROM {table} WHERE {col} = {q(val)})"

def base_db():
    c = sqlite3.connect(':memory:'); c.execute('PRAGMA foreign_keys=ON')
    c.executescript(open(os.path.join(DB_DIR, 'schema.sql')).read())
    for f in sorted(glob.glob(os.path.join(DB_DIR, 'seed', '0*.sql'))):
        c.executescript(open(f).read())
    return c

def build(name, tools, ref):
    errs, out = [], [f'-- Generated by db/tools/build_seed.py from db/data/{name}.json. Do not edit by hand.', '']
    specs = {k: (t, e) for k, t, e in ref.execute('SELECT key, data_type, enum_values FROM spec_definition')}
    feats = {r[0] for r in ref.execute('SELECT slug FROM feature')}
    for t in tools:
        tid = sel('tool', 'slug', t['slug'])
        for key, table in [('brand', 'brand'), ('category', 'category'), ('platform', 'platform'), ('line', 'product_line')]:
            v = t.get(key)
            if v is not None and not ref.execute(f'SELECT 1 FROM {table} WHERE slug=?', (v,)).fetchone():
                errs.append(f"{t['slug']}: unknown {key} '{v}'")
        out.append(f"INSERT INTO tool (brand_id, category_id, platform_id, product_line_id, model, slug, name, power_source, motor_type, status, country_of_origin, official_url, notes) VALUES ("
                   f"{sel('brand','slug',t['brand'])}, {sel('category','slug',t['category'])}, {sel('platform','slug',t.get('platform'))}, "
                   f"{sel('product_line','slug',t.get('line'))}, {q(t['model'])}, {q(t['slug'])}, {q(t['name'])}, {q(t.get('power','battery'))}, "
                   f"{q(t.get('motor'))}, {q(t.get('status','active'))}, {q(t.get('origin'))}, {q(t.get('url'))}, {q(t.get('notes'))});")
        cat_ok = {r[0] for r in ref.execute('SELECT sd.key FROM category_spec cs JOIN spec_definition sd ON sd.id=cs.spec_id JOIN category c ON c.id=cs.category_id WHERE c.slug=?', (t['category'],))}
        for key, qual, val, raw, src, url in t.get('specs', []):
            if key not in specs: errs.append(f"{t['slug']}: unknown spec '{key}'"); continue
            if key not in cat_ok: errs.append(f"{t['slug']}: spec '{key}' not used for category {t['category']}")
            dtype, enum = specs[key]
            num = mn = mx = b = txt = None
            if dtype == 'number':
                if not isinstance(val, (int, float)) or isinstance(val, bool): errs.append(f"{t['slug']}.{key}: expected number, got {val!r}")
                num = val
            elif dtype == 'range':
                if not (isinstance(val, list) and len(val) == 2): errs.append(f"{t['slug']}.{key}: expected [min,max]")
                else: mn, mx = val
            elif dtype == 'bool':
                if not isinstance(val, bool): errs.append(f"{t['slug']}.{key}: expected true/false")
                b = val
            else:
                if not isinstance(val, str): errs.append(f"{t['slug']}.{key}: expected text")
                if dtype == 'enum' and val not in json.loads(enum): errs.append(f"{t['slug']}.{key}: '{val}' not in {enum}")
                txt = val
            stype = {'M': 'manufacturer', 'R': 'retailer', 'O': 'other'}.get(src)
            if not stype: errs.append(f"{t['slug']}.{key}: source must be M, R or O")
            if not url: errs.append(f"{t['slug']}.{key}: missing source url")
            out.append(f"INSERT INTO tool_spec (tool_id, spec_id, qualifier, value_num, value_min, value_max, value_bool, value_text, raw_text, source_type, source_url, retrieved_on) VALUES ("
                       f"{tid}, {sel('spec_definition','key',key)}, {q(qual)}, {q(num)}, {q(mn)}, {q(mx)}, {q(b)}, {q(txt)}, {q(raw)}, {q(stype)}, {q(url)}, {q(TODAY)});")
        for f, term in t.get('features', []):
            if f not in feats: errs.append(f"{t['slug']}: unknown feature '{f}'")
            out.append(f"INSERT INTO tool_feature (tool_id, feature_id, brand_term) VALUES ({tid}, {sel('feature','slug',f)}, {q(term)});")
        for claim, cond, url in t.get('claims', []):
            out.append(f"INSERT INTO tool_claim (tool_id, claim, conditions, source_url, retrieved_on) VALUES ({tid}, {q(claim)}, {q(cond)}, {q(url)}, {q(TODAY)});")
        for s in t.get('skus', []):
            sid = f"(SELECT id FROM sku WHERE model_number = {q(s['model'])} AND brand_id = {sel('brand','slug',t['brand'])})"
            out.append(f"INSERT INTO sku (brand_id, model_number, title, sku_type, upc, status, official_url) VALUES ("
                       f"{sel('brand','slug',t['brand'])}, {q(s['model'])}, {q(s['title'])}, {q(s['type'])}, {q(s.get('upc'))}, {q(s.get('status','active'))}, {q(s.get('url'))});")
            for r in s.get('ratings', []):
                if not ref.execute('SELECT 1 FROM retailer WHERE slug=?', (r['retailer'],)).fetchone(): errs.append(f"{s['model']}: unknown retailer {r['retailer']}")
                out.append(f"INSERT INTO rating_snapshot (sku_id, retailer_id, observed_on, avg_rating, review_count, url) VALUES ({sid}, {sel('retailer','slug',r['retailer'])}, {q(TODAY)}, {q(r.get('avg'))}, {q(r.get('count'))}, {q(r['url'])});")
            for qty, kind, ref_ in s.get('items', []):
                tool_ = sel('tool', 'slug', ref_) if kind == 'tool' else 'NULL'
                bat = f"(SELECT id FROM battery WHERE model = {q(ref_)})" if kind == 'battery' else 'NULL'
                text = q(ref_) if kind == 'text' else 'NULL'
                if kind not in ('tool', 'battery', 'text'): errs.append(f"{s['model']}: bad item kind {kind}")
                out.append(f"INSERT INTO sku_item (sku_id, qty, tool_id, battery_id, charger_id, item_text) VALUES ({sid}, {qty}, {tool_}, {bat}, NULL, {text});")
        out.append('')
    return errs, '\n'.join(out) + '\n'

def build_batteries(bats, ref):
    errs, out = [], ['-- Generated by db/tools/build_seed.py from db/data/batteries.json. Do not edit by hand.', '']
    for b in bats:
        for key, table in [('brand', 'brand'), ('platform', 'platform'), ('line', 'product_line')]:
            v = b.get(key)
            if v is not None and not ref.execute(f'SELECT 1 FROM {table} WHERE slug=?', (v,)).fetchone():
                errs.append(f"battery {b['model']}: unknown {key} '{v}'")
        if ref.execute('SELECT 1 FROM battery WHERE model=?', (b['model'],)).fetchone():
            continue  # already in an earlier seed file
        out.append(f"INSERT INTO battery (brand_id, platform_id, product_line_id, model, name, capacity_ah, capacity_ah_alt, energy_wh, weight_lb, fuel_gauge, official_url, notes) VALUES ("
                   f"{sel('brand','slug',b['brand'])}, {sel('platform','slug',b['platform'])}, {sel('product_line','slug',b.get('line'))}, {q(b['model'])}, {q(b['name'])}, "
                   f"{q(b.get('ah'))}, {q(b.get('ah_alt'))}, {q(b.get('wh'))}, {q(b.get('weight'))}, {q(b.get('fuel_gauge'))}, {q(b.get('url'))}, {q(b.get('notes'))});")
    return errs, '\n'.join(out) + '\n'

def main():
    ref = base_db()
    files = sorted(glob.glob(os.path.join(DB_DIR, 'data', '*.json')))
    all_errs, built = [], []
    files.sort(key=lambda f: (os.path.basename(f) != 'batteries.json', f))  # batteries first
    for i, f in enumerate(files):
        name = os.path.splitext(os.path.basename(f))[0]
        tools = json.load(open(f))
        if name == 'batteries':
            errs, sql = build_batteries(tools, ref)
            all_errs += errs
            if not errs:
                ref.executescript(sql); built.append((name, sql, len(tools)))
            continue
        slugs = [t['slug'] for t in tools]
        dup = {s for s in slugs if slugs.count(s) > 1}
        if dup: all_errs.append(f'{name}: duplicate slugs {dup}')
        errs, sql = build(name, tools, ref)
        all_errs += errs
        if not errs:
            try:
                ref.executescript(sql)
            except sqlite3.Error as e:
                all_errs.append(f'{name}: SQL error {e}')
            built.append((name, sql, len(tools)))
    fk = ref.execute('PRAGMA foreign_key_check').fetchall()
    if fk: all_errs.append(f'foreign key problems: {fk[:5]}')
    if all_errs:
        print('NOT WRITTEN. Fix these first:'); print('\n'.join('  - ' + e for e in all_errs)); sys.exit(1)
    for n, (name, sql, count) in enumerate(built):
        path = os.path.join(DB_DIR, 'seed', f'1{n}_{name}.sql')
        open(path, 'w', newline='\n').write(sql)
        print(f'wrote seed/1{n}_{name}.sql ({count} tools)')
    print('tools in database:', ref.execute('SELECT count(*) FROM tool').fetchone()[0],
          '| spec values:', ref.execute('SELECT count(*) FROM tool_spec').fetchone()[0])

if __name__ == '__main__':
    main()